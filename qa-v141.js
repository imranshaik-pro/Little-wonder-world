/* Browser-level regression for v1.4.1 restoration. Real-device QA remains required. */
const fs=require('fs'),path=require('path'),assert=require('assert');
const {chromium}=require('/opt/codex/runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root=__dirname;
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/tmp/lww-v2-tools/chrome-headless-shell-linux64/chrome-headless-shell',args:['--no-sandbox']});
 const checks=[];
 try{
  for(const viewport of [{width:2400,height:1080},{width:1000,height:480}]){
   const page=await browser.newPage({viewport});
   const errors=[],missing=[];
   page.on('pageerror',err=>errors.push(err.message));
   page.on('requestfailed',req=>missing.push(req.url()+': '+req.failure()?.errorText));
   await page.route('**/release.js',route=>route.fulfill({contentType:'text/javascript',body:fs.readFileSync(path.join(root,'releases','v1.4.1.js'),'utf8')}));
   await page.goto('file://'+path.join(root,'app/src/main/assets/index.html'));
   await page.evaluate(()=>{localStorage.clear();location.reload();});
   await page.waitForSelector('[data-action="enter"]');
   await page.click('[data-action="enter"]');
   assert.strictEqual(await page.evaluate(()=>release.id),'v1.4.1');
   // Explicitly preserve the six promised v1.4 quality improvements.
   await page.evaluate(()=>beginMode('alphabet','letterhunt'));
   const letterTiles=await page.locator('.letter-choice .choice-icon').allTextContents();
   assert(letterTiles.length>=3&&letterTiles.every(s=>/^[A-Z]$/.test(s)),'Letter Hunt shows actual letters');
   const missionBox=await page.locator('.mission').boundingBox();
   const shellBox=await page.locator('.game-shell').boundingBox();
   assert(missionBox.width/shellBox.width>.92,'Instructions use a full-width horizontal strip');
   await page.evaluate(()=>beginMode('tracing','shapes'));
   const shapeBox=await page.locator('.trace-pad').boundingBox();
   const shapeField=await page.locator('.playfield').boundingBox();
   assert(shapeBox.width/shapeField.width>.88,'Shape tracing uses nearly all available width');
   assert(await page.locator('[data-action="nextTrace"]').count(),'Tracing Next control visible');
   assert(await page.locator('[data-action="skipTrace"]').count(),'Tracing Skip control visible');
   assert(await page.locator('#traceProgressFill').count(),'Tracing progress bar visible');
   await page.evaluate(()=>{beginMode('tracing','capitals');state.round=2;state.traceLength=0;state.traceReady=false;render();});
   const traceCanvas=await page.locator('#traceCanvas').boundingBox();
   await page.mouse.move(traceCanvas.x+traceCanvas.width*.3,traceCanvas.y+traceCanvas.height*.33);
   await page.mouse.down();
   await page.mouse.move(traceCanvas.x+traceCanvas.width*.67,traceCanvas.y+traceCanvas.height*.65,{steps:12});
   await page.mouse.up();
   await page.waitForTimeout(1600);
   assert.strictEqual(await page.evaluate(()=>state.round),3,'Tracing automatically advances from C to D');
   await page.evaluate(()=>{state.screen='home';render();});
   await page.click('[data-action="land"][data-value="discovery"]');
   assert.strictEqual(await page.locator('[data-action="world"]').first().getAttribute('data-value'),'flashbook','Flashcard world prominent in Discovery');
   await page.click('[data-action="world"][data-value="flashbook"]');
   assert.strictEqual(await page.locator('[data-action="mode"]').count(),9,'Themed flashcards first page');
   await page.click('[data-action="mode"][data-value="vehicles"]');
   assert(await page.locator('.flashcard-illustration').count(),'Themed flashcards actually open');
   await page.evaluate(()=>beginMode('animals','flashcards'));
   assert.strictEqual(await page.evaluate(()=>cardCollection().length),123,'Full atlas opens first');
   assert(await page.locator('.flashcard-filter').getByText('All 123 animals').count());
   await page.evaluate(()=>{state.cardIndex=cardCollection().findIndex(a=>a.name==='Elephant');render();});
   const illust=page.locator('.flash-real-photo');
   await illust.waitFor();
   assert.strictEqual(await illust.evaluate(img=>img.complete&&img.naturalWidth>0),true,'Elephant illustration loads locally');
   assert(await page.getByText('Savannas and forests').count(),'Details visible');
   await page.screenshot({path:path.join(root,'qa-v141-atlas-'+viewport.width+'.png')});
   await page.click('[data-action="viewFilm"]');
   assert.strictEqual(await page.evaluate(()=>state.mode),'realfilms');
   assert.strictEqual(await page.evaluate(()=>cardCollection().length),6);
   assert(await page.locator('video[src$="elephant.webm"]').count(),'Elephant film reachable from atlas');
   assert(await page.locator('[data-action="animalVideo"]').count(),'Large film has Replay control');
   const videoBox=await page.locator('.flash-video').boundingBox();
   const filmField=await page.locator('.playfield').boundingBox();
   assert(videoBox.width/filmField.width>.44,'Real film is a main visual, not a tiny thumbnail');
   await page.screenshot({path:path.join(root,'qa-v141-film-'+viewport.width+'.png')});
   await page.click('[data-action="openAnimalAtlas"]');
   assert.strictEqual(await page.evaluate(()=>cardCollection().length),123,'Full atlas restored after video');
   await page.click('[data-action="cardFilter"][data-value="sounds"]');
   assert.strictEqual(await page.evaluate(()=>cardCollection().length),34,'34 recorded/effect sound cards');
   await page.evaluate(()=>beginMode('animals','objectcards'));
   assert.strictEqual(await page.evaluate(()=>cardCollection().length),45,'45 object cards');
   await page.evaluate(()=>beginMode('family','familycards'));
   assert(await page.getByText('Ask a grown-up to add photos').count(),'Family no-data state');
   await page.evaluate(()=>beginMode('body','doorstory'));
   assert(await page.locator('[data-action="doorChoose"]').count(),'Door safety remains interactive');
   const paused=await page.evaluate(()=>{window.wonderPause();return {active:appActive,backgroundPaused:!backgroundMusic||backgroundMusic.paused}});
   assert(!paused.active&&paused.backgroundPaused,'Backgrounding pauses music and media');
   await page.evaluate(()=>window.wonderResume());
   assert.strictEqual(await page.evaluate(()=>appActive),true,'Foreground media state can resume');
   const dimensions=await page.evaluate(()=>({bodyScroll:document.body.scrollHeight,window:innerHeight}));
   assert(dimensions.bodyScroll<=dimensions.window+5,'Child screen should not force scrolling');
   assert.deepStrictEqual(errors,[],'No JS page errors');
   assert.deepStrictEqual(missing,[],'All requested assets load');
   checks.push({viewport,atlas:123,animalAudio:34,objects:45,films:6,letters:letterTiles,traceAdvancedFromC:true,filmWidthPct:Math.round(100*videoBox.width/filmField.width),dimensions,errors,missing});
   await page.close();
  }
  console.log(JSON.stringify(checks,null,2));
 }finally{await browser.close();}
})().catch(err=>{console.error(err);process.exit(1)});
